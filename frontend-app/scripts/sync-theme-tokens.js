#!/usr/bin/env node
/**
 * sync-theme-tokens — regenerates src/theme/tokens.generated.js from the web
 * app's centralized palette (frontend/src/index.css, the `:root` block).
 *
 * The web app is the single source of truth for every color. React Native
 * cannot read CSS custom properties, so this script resolves each variable
 * once into a concrete value:
 *
 *   --name: H S% L%        → hsl['name']  = '#rrggbb'      (semantic tokens)
 *   --name: H S% L% / A    → hsl['name']  = 'rgba(r,g,b,A)'
 *   --name-rgb: R G B      → rgb['name']  = [r, g, b]       (channel tokens)
 *   --name: #hex           → raw['name']  = '#hex'
 *   --radius: 0.75rem      → raw['radius'] = '0.75rem'
 *
 * Run from frontend-app/:  node scripts/sync-theme-tokens.js
 * (also exposed as `yarn theme:sync`). Never edit the generated file by hand.
 */
const fs = require('fs');
const path = require('path');

const WEB_CSS = path.resolve(__dirname, '../../frontend/src/index.css');
const OUT = path.resolve(__dirname, '../src/theme/tokens.generated.js');

function hslToRgb(h, s, l) {
  s /= 100;
  l /= 100;
  const k = n => (n + h / 30) % 12;
  const a = s * Math.min(l, 1 - l);
  const f = n =>
    l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)));
  return [f(0), f(8), f(4)].map(v => Math.round(v * 255));
}

const toHex = rgb =>
  '#' + rgb.map(v => v.toString(16).padStart(2, '0')).join('');

const css = fs.readFileSync(WEB_CSS, 'utf8');
const rootMatch = /:root\s*\{([\s\S]*?)\n\s*\}/.exec(css);
if (!rootMatch) {
  console.error('Could not find a :root block in', WEB_CSS);
  process.exit(1);
}
const body = rootMatch[1].replace(/\/\*[\s\S]*?\*\//g, '');

const hsl = {};
const rgb = {};
const raw = {};

for (const m of body.matchAll(/--([a-z0-9-]+)\s*:\s*([^;]+);/gi)) {
  const name = m[1];
  const value = m[2].trim();

  const rgbMatch = /^(\d+)\s+(\d+)\s+(\d+)$/.exec(value);
  if (name.endsWith('-rgb') && rgbMatch) {
    rgb[name.slice(0, -4)] = rgbMatch.slice(1, 4).map(Number);
    continue;
  }
  const hslMatch =
    /^(-?[\d.]+)\s+([\d.]+)%\s+([\d.]+)%(?:\s*\/\s*([\d.]+))?$/.exec(value);
  if (hslMatch) {
    const [r, g, b] = hslToRgb(
      Number(hslMatch[1]),
      Number(hslMatch[2]),
      Number(hslMatch[3]),
    );
    hsl[name] =
      hslMatch[4] !== undefined
        ? `rgba(${r},${g},${b},${hslMatch[4]})`
        : toHex([r, g, b]);
    continue;
  }
  raw[name] = value;
}

const banner = `/* eslint-disable */
// GENERATED by scripts/sync-theme-tokens.js from frontend/src/index.css.
// Do not edit by hand — change the web palette, then run \`yarn theme:sync\`.
// CommonJS on purpose: tailwind.config.js require()s this file at build time.
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(
  OUT,
  `${banner}module.exports = ${JSON.stringify({ hsl, rgb, raw }, null, 2)};\n`,
);
console.log(
  `Wrote ${path.relative(process.cwd(), OUT)}: ${
    Object.keys(hsl).length
  } hsl, ` +
    `${Object.keys(rgb).length} rgb, ${Object.keys(raw).length} raw tokens.`,
);
