#!/usr/bin/env node
// Generates the local gateway's nginx config from shared/service-routes.json, the same rules
// the AWS ALB uses (docs/auth-users-split.md, 13.1), so local and AWS routing can't drift.
//
//   node scripts/sync-gateway.mjs          rewrite local/gateway/nginx.conf
//   node scripts/sync-gateway.mjs --check  exit 1 if it's stale (CI)
//
// No dependencies: plain Node 18+.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = 'shared/service-routes.json';
const OUTPUT = 'local/gateway/nginx.conf';
const CHECK = process.argv.includes('--check');

// Until today's backend is removed (build plan 8.6), paths no new service claims go to it, so
// the old and new code can run side by side locally. The ALB has no such fallback.
const LEGACY_FALLBACK = 'backend';

function fail(msg) {
  console.error(`${SOURCE}: ${msg}`);
  process.exit(1);
}

let data;
try {
  data = JSON.parse(fs.readFileSync(path.join(ROOT, SOURCE), 'utf8'));
} catch (err) {
  fail(`cannot read/parse: ${err.message}`);
}

const SERVICE_RE = /^[a-z][a-z0-9-]{0,30}$/;
// ALB path patterns: case-sensitive, up to 128 characters, A–Z a–z 0–9 _ - . $ / ~ " ' @ : +
// plus the wildcards * and ?. This file uses only *, and a narrower character set.
const PATTERN_RE = /^\/[A-Za-z0-9_\-./*]{0,127}$/;

const { port, rules } = data;
if (!Number.isInteger(port) || port < 1 || port > 65535) fail('"port" must be a TCP port');
if (!Array.isArray(rules) || rules.length === 0) fail('"rules" must be a non-empty array');

const priorities = new Set();
const patterns = new Set();
let previous = 0;
for (const rule of rules) {
  const { priority, service, paths, built = true } = rule;
  if (!Number.isInteger(priority) || priority < 1 || priority > 49999) {
    fail(`priority ${JSON.stringify(priority)}: must be 1–49999 (50000 is the fixed 404)`);
  }
  if (priorities.has(priority)) fail(`priority ${priority} used twice`);
  if (priority <= previous) fail(`priority ${priority}: rules must be in ascending priority order`);
  priorities.add(priority);
  previous = priority;
  if (!SERVICE_RE.test(service ?? '')) fail(`priority ${priority}: invalid service ${JSON.stringify(service)}`);
  if (typeof built !== 'boolean') fail(`priority ${priority}: "built" must be true or false`);
  // AWS allows 5 condition values per rule; 2 go to the X-Origin-Verify header (13.1).
  if (!Array.isArray(paths) || paths.length === 0 || paths.length > 3) {
    fail(`priority ${priority}: 1–3 paths per rule`);
  }
  for (const p of paths) {
    if (!PATTERN_RE.test(p)) fail(`priority ${priority}: invalid path pattern ${JSON.stringify(p)}`);
    if (patterns.has(p)) fail(`path pattern ${p} listed twice`);
    patterns.add(p);
  }
}

// ALB pattern → anchored regex: escape everything, then * becomes "any characters".
const toRegex = (pattern) => `^${pattern.replace(/[.+?^${}()|[\]\\]/g, '\\$&').replace(/\*/g, '.*')}$`;

function render() {
  const lines = [
    `# Generated by scripts/sync-gateway.mjs from ${SOURCE} — do not edit.`,
    `# Edit ${SOURCE}, then run \`node scripts/sync-gateway.mjs\`.`,
    '#',
    '# Local stand-in for the ALB path rules (docs/auth-users-split.md, 13.1). Regex locations',
    '# are tried in order, so the rules keep their ALB priority order.',
    'server {',
    '    listen 8080;',
    '',
    "    # Docker's DNS, looked up per request: a service that isn't running gets 502, not a",
    '    # gateway that refuses to start.',
    '    resolver 127.0.0.11 valid=10s ipv6=off;',
    '',
    '    # Voice uploads are up to 10 MB (POST /api/v1/speech/transcriptions).',
    '    client_max_body_size 12m;',
    '',
    '    proxy_set_header Host $host;',
    '    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;',
    '    proxy_set_header X-Forwarded-Proto $scheme;',
    '    proxy_set_header X-Request-Id $request_id;',
    '',
    '    location = /gateway/health {',
    '        access_log off;',
    '        default_type text/plain;',
    '        return 200 "ok\\n";',
    '    }',
  ];
  for (const { priority, service, paths, built = true } of rules) {
    lines.push('');
    if (!built) {
      lines.push(`    # ${priority} ${service}: not built yet, so not routed (${paths.join(', ')}).`);
      continue;
    }
    for (const p of paths) {
      lines.push(
        `    # ${priority} ${service}: ${p}`,
        `    location ~ ${toRegex(p)} {`,
        `        set $upstream ${service};`,
        `        proxy_pass http://$upstream:${port};`,
        '    }',
      );
    }
  }
  lines.push(
    '',
    '    # Until build plan 8.6: anything else under /api/ goes to today\'s backend.',
    '    location /api/ {',
    `        set $upstream ${LEGACY_FALLBACK};`,
    `        proxy_pass http://$upstream:${port};`,
    '    }',
    '',
    '    # The ALB\'s fixed 404 (priority 50000).',
    '    location / {',
    '        return 404;',
    '    }',
    '}',
  );
  return lines.join('\n') + '\n';
}

const content = render();
const file = path.join(ROOT, OUTPUT);

// Compares (and, unless --check, rewrites) the file through one file descriptor rather than
// separate path-based calls, so it can't be swapped between the check and the write
// (CWE-367 / CodeQL js/file-system-race), as scripts/sync-routing.mjs does.
function syncFile() {
  if (!CHECK) fs.mkdirSync(path.dirname(file), { recursive: true });
  let fd;
  try {
    fd = fs.openSync(file, CHECK ? 'r' : fs.constants.O_RDWR | fs.constants.O_CREAT);
  } catch (err) {
    if (CHECK && err.code === 'ENOENT') return true; // missing counts as stale
    throw err;
  }
  try {
    if (fs.readFileSync(fd, 'utf8') === content) return false;
    if (!CHECK) {
      fs.ftruncateSync(fd, 0);
      fs.writeSync(fd, content, 0, 'utf8');
    }
    return true;
  } finally {
    fs.closeSync(fd);
  }
}

const stale = syncFile();
if (CHECK && stale) {
  console.error(`Stale generated file (run \`node scripts/sync-gateway.mjs\`):\n  ${OUTPUT}`);
  process.exit(1);
}
console.log(stale ? `Updated: ${OUTPUT}` : `${OUTPUT} is up to date (${rules.length} rules).`);
